// edit.js — guarded file mutations for the write path.
//
// Every write goes through: path safety (escape-proof) → denylist policy
// (workflows, secrets, VCS internals are NEVER agent-editable) → mutation
// ledger entry. The ledger becomes the PR audit trail.
import fs from 'node:fs';
import path from 'node:path';
import { BuddyError, globMatches, truncate } from '../util.js';

export const WRITE_DENYLIST = [
  '.github/**', // workflow privilege escalation — hard no
  '**/.git/**',
  '**/.env*',
  '**/*.pem',
  '**/*.key',
  '**/*.p12',
  '**/secrets.*',
  '**/*credentials*',
  '**/*.lock', // lock files are regenerated by package managers, not by hand
  'package-lock.json',
  'yarn.lock',
  'pnpm-lock.yaml',
];

export class MutationLedger {
  constructor() {
    this.entries = [];
  }

  add(entry) {
    this.entries.push({ ...entry, at: new Date().toISOString() });
  }

  get filesChanged() {
    return [...new Set(this.entries.filter((e) => e.op !== 'failed').map((e) => e.path))];
  }

  totalLines() {
    return this.entries
      .filter((e) => e.op !== 'failed')
      .reduce((n, e) => n + (e.linesAdded || 0) + (e.linesRemoved || 0), 0);
  }

  toMarkdown() {
    if (!this.entries.length) return '_No file changes._';
    const rows = this.entries.map(
      (e) => `| \`${e.path}\` | ${e.op}${e.failed ? ' ❌' : ''} | ${e.linesAdded ?? 0}+ / ${e.linesRemoved ?? 0}− | ${truncate(e.reason || '', 120).replace(/\|/g, '\\|')} |`
    );
    return ['| File | Op | Lines | Reason |', '|---|---|---|---|', ...rows].join('\n');
  }
}

export class RepoEditor {
  /**
   * @param {object} localRepo  LocalRepo instance (root resolution + safety)
   * @param {object} opts { denyPaths, maxFiles, maxLines, ledger }
   */
  constructor(localRepo, { denyPaths = WRITE_DENYLIST, maxFiles = 10, maxLines = 600, ledger = new MutationLedger() } = {}) {
    this.repo = localRepo;
    this.denyPaths = denyPaths;
    this.maxFiles = maxFiles;
    this.maxLines = maxLines;
    this.ledger = ledger;
  }

  _policyCheck(rel) {
    const p = String(rel || '');
    if (!p || p.startsWith('/') || p.includes('..')) {
      throw new BuddyError(`edit: unsafe path "${p}"`, { code: 'UNSAFE_PATH' });
    }
    if (this.denyPaths.some((g) => globMatches(g, p))) {
      throw new BuddyError(`edit: path is protected by policy: ${p}`, { code: 'DENIED_PATH' });
    }
  }

  _budgetCheck(rel, linesAdded = 0, linesRemoved = 0) {
    if (!this.ledger.filesChanged.includes(rel) && this.ledger.filesChanged.length >= this.maxFiles) {
      throw new BuddyError(`edit: file budget reached (${this.maxFiles} files)`, { code: 'BUDGET_FILES' });
    }
    const projected = this.ledger.totalLines() + linesAdded + linesRemoved;
    if (projected > this.maxLines) {
      throw new BuddyError(`edit: line budget reached (${projected}/${this.maxLines})`, { code: 'BUDGET_LINES' });
    }
  }

  /** Overwrite or create a file. */
  writeFile(rel, content, { reason = '' } = {}) {
    this._policyCheck(rel);
    const abs = this.repo.resolveSafe(rel);
    let before = '';
    try {
      before = fs.readFileSync(abs, 'utf8');
    } catch {
      before = '';
    }
    const beforeLines = before ? before.split('\n').length : 0;
    const afterLines = String(content).split('\n').length;
    this._budgetCheck(rel, afterLines, beforeLines);
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, String(content), 'utf8');
    const op = before ? 'rewrite' : 'create';
    this.ledger.add({ path: rel, op, linesAdded: before ? Math.max(0, afterLines - beforeLines) : afterLines, linesRemoved: Math.max(0, beforeLines - afterLines), reason });
    return { path: rel, op, bytes: String(content).length };
  }

  /** Replace an exact snippet. Fails unless the snippet occurs exactly once. */
  replaceInFile(rel, find, replace, { reason = '' } = {}) {
    this._policyCheck(rel);
    const abs = this.repo.resolveSafe(rel);
    let content;
    try {
      content = fs.readFileSync(abs, 'utf8');
    } catch {
      throw new BuddyError(`replace: file not found: ${rel}`, { code: 'NO_FILE' });
    }
    const findStr = String(find);
    const count = content.split(findStr).length - 1;
    if (count === 0) throw new BuddyError(`replace: snippet not found in ${rel} — re-read the file and retry`, { code: 'NO_MATCH' });
    if (count > 1) throw new BuddyError(`replace: snippet matches ${count} times in ${rel} — include more context to make it unique`, { code: 'AMBIGUOUS' });
    const next = content.replace(findStr, String(replace));
    const linesAdded = String(replace).split('\n').length;
    const linesRemoved = findStr.split('\n').length;
    this._budgetCheck(rel, linesAdded, linesRemoved);
    fs.writeFileSync(abs, next, 'utf8');
    this.ledger.add({ path: rel, op: 'replace', linesAdded, linesRemoved, reason });
    return { path: rel, op: 'replace', linesAdded, linesRemoved };
  }

  /** Append content at end of file (creates the file if missing). */
  appendToFile(rel, content, { reason = '' } = {}) {
    this._policyCheck(rel);
    const abs = this.repo.resolveSafe(rel);
    let before = '';
    try {
      before = fs.readFileSync(abs, 'utf8');
    } catch {
      before = '';
    }
    const add = String(content);
    this._budgetCheck(rel, add.split('\n').length, 0);
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, (before && !before.endsWith('\n') ? before + '\n' : before) + add, 'utf8');
    this.ledger.add({ path: rel, op: before ? 'append' : 'create', linesAdded: add.split('\n').length, linesRemoved: 0, reason });
    return { path: rel, op: 'append' };
  }

  /** Build agent-facing file tools wired to this editor. */
  toTools(repoReader, { maxFileChars = 30000 } = {}) {
    return [
      {
        name: 'read_file',
        description: 'Read a repository file (capped). Read before editing anything.',
        args: '{"path":"src/file.js"}',
        run: async ({ path: p }) => {
          const r = repoReader.readFile(p, maxFileChars);
          return r ? `FILE ${p}:\n${r.content}` : `ERROR: cannot read ${p}`;
        },
      },
      {
        name: 'write_file',
        description: 'Create or fully rewrite a file. Use replace_in_file for surgical edits.',
        args: '{"path":"src/file.js","content":"full new file content"}',
        run: async ({ path: p, content }) => {
          if (typeof content !== 'string' || !content.trim()) return 'ERROR: content required';
          try {
            const r = this.writeFile(p, content, { reason: 'agent edit' });
            return `OK ${r.op} ${p} (${r.bytes} bytes)`;
          } catch (e) {
            this.ledger.add({ path: p, op: 'failed', reason: e.message });
            return `ERROR: ${e.message}`;
          }
        },
      },
      {
        name: 'replace_in_file',
        description: 'Replace an exact unique snippet in a file.',
        args: '{"path":"src/file.js","find":"exact existing snippet","replace":"new snippet"}',
        run: async ({ path: p, find, replace }) => {
          if (typeof find !== 'string' || !find) return 'ERROR: find required';
          try {
            const r = this.replaceInFile(p, find, String(replace ?? ''), { reason: 'agent edit' });
            return `OK replaced ${r.linesRemoved}→${r.linesAdded} lines in ${p}`;
          } catch (e) {
            this.ledger.add({ path: p, op: 'failed', reason: e.message });
            return `ERROR: ${e.message}`;
          }
        },
      },
      {
        name: 'append_to_file',
        description: 'Append lines to the end of a file.',
        args: '{"path":"README.md","content":"text to append"}',
        run: async ({ path: p, content }) => {
          if (typeof content !== 'string' || !content.trim()) return 'ERROR: content required';
          try {
            const r = this.appendToFile(p, content, { reason: 'agent edit' });
            return `OK ${r.op} ${p}`;
          } catch (e) {
            this.ledger.add({ path: p, op: 'failed', reason: e.message });
            return `ERROR: ${e.message}`;
          }
        },
      },
      {
        name: 'list_files',
        description: 'List repository files.',
        args: '{"dir":"src"}',
        run: async ({ dir = '' } = {}) => repoReader.listFiles(dir, { max: 200 }).join('\n') || '(empty)',
      },
      {
        name: 'search_code',
        description: 'Search the repository (substring or regex).',
        args: '{"needle":"pattern","regex":false}',
        run: async ({ needle, regex = false } = {}) => {
          const hits = repoReader.search(String(needle), { regex: Boolean(regex), max: 15 });
          return hits.map((h) => `${h.file}:${h.line}: ${h.text}`).join('\n') || '(no matches)';
        },
      },
    ];
  }
}
